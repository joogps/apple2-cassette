def bezier(p0, p1, p2, p3, t):
    u = 1 - t
    return tuple(u**3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t**3 * d
                 for a, b, c, d in zip(p0, p1, p2, p3))


def arc_length(seg, n=20):
    pts = [bezier(*seg, i / n) for i in range(n + 1)]
    return sum(math.dist(a, b) for a, b in zip(pts, pts[1:]))


def sample_path(segments, density=0.12):
    pts = [segments[0][0]]
    for seg in segments:
        n = max(3, min(16, int(arc_length(seg) * density)))
        pts += [bezier(*seg, i / n) for i in range(1, n + 1)]
    return pts


# Map SVG space (content ~7..629 x 7..192) onto 280x192 hi-res, 4px margin
SVG_X0, SVG_X1, SVG_Y0, SVG_Y1 = 7, 629, 7, 192
MARGIN = 4
SCALE = min((280 - 2 * MARGIN) / (SVG_X1 - SVG_X0), (192 - 2 * MARGIN) / (SVG_Y1 - SVG_Y0))
OFF_X = MARGIN + ((280 - 2 * MARGIN) - (SVG_X1 - SVG_X0) * SCALE) / 2
OFF_Y = MARGIN + ((192 - 2 * MARGIN) - (SVG_Y1 - SVG_Y0) * SCALE) / 2


def to_screen(p):
    x = round((p[0] - SVG_X0) * SCALE + OFF_X)
    y = round((p[1] - SVG_Y0) * SCALE + OFF_Y)
    return max(0, min(279, x)), max(0, min(191, y))


def dedup(pts):
    out = [pts[0]]
    for p in pts[1:]:
        if p != out[-1]:
            out.append(p)
    return out


def hplot_lines(coords, linenum, step=5, max_len=200):
    """One HPLOT chain, split across BASIC lines with HPLOT TO continuations."""
    lines = []
    cur = f"HPLOT {coords[0][0]},{coords[0][1]}"
    for x, y in coords[1:]:
        seg = f" TO {x},{y}"
        if len(cur + seg) > max_len:
            lines.append((linenum, cur))
            linenum += step
            cur = f"HPLOT TO {x},{y}"
        else:
            cur += seg
    lines.append((linenum, cur))
    return lines, linenum + step


